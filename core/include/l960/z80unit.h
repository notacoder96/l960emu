// One of the two Z80 control processors on the reverb card, with its dual-port RAM, banked SRAM and the
// pair of Lexichips it drives. Memory map from the 960L service manual, p. 7-38:
//   $0000-$07FE  dual-port SRAM (code + messages, loaded by the 56301)
//   $07FF        mailbox: Z80 write -> interrupt to 56301 (DB_MAS_INT), 56301 write to $7FE -> INTL to Z80
//   $3000-$3BFF  Lexichip A internal decodes
//   $4000-$7FFF  16 KB window, 4 banks of SRAM
//   $8000-$8BFF  Lexichip B internal decodes
//   $C000-$FFFF  16 KB window, 4 banks of SRAM
#pragma once

#include "l960/lexichip.h"

#include <array>
#include <cstdint>
#include <functional>
#include <memory>

namespace l960
{
	// 2 KB dual-port SRAM with the IDT-style mailbox at the top two addresses
	class Dpram
	{
	public:
		static constexpr uint16_t Size = 0x800;
		static constexpr uint16_t MailboxToZ80 = 0x7FE;  // written by the 56301 (right port)
		static constexpr uint16_t MailboxTo56k = 0x7FF;  // written by the Z80 (left port)

		uint8_t readLeft(uint16_t _a);                 // Z80 side
		void writeLeft(uint16_t _a, uint8_t _v);
		uint8_t readRight(uint16_t _a);                // 56301 side (reading $7FF clears the 56301 interrupt)
		void writeRight(uint16_t _a, uint8_t _v);

		bool intToZ80() const { return m_intL; }       // INTL, routed to Lexichip A status bit 6
		bool intTo56k() const { return m_intR; }       // INTR -> 56301 IRQC/IRQD

		std::array<uint8_t, Size>& data() { return m_mem; }
		void reset() { m_mem.fill(0); m_intL = m_intR = false; }

		// Debugging: mailbox writes ('Z' = by the Z80, 'D' = by the 56301)
		std::function<void(char side, uint16_t addr, uint8_t value)> onMailbox;

	private:
		std::array<uint8_t, Size> m_mem{};
		bool m_intL = false, m_intR = false;
	};

	class Z80Unit
	{
	public:
		static constexpr uint32_t SramBanks = 8, BankSize = 0x4000;

		Z80Unit(Dpram& _dpram, Lexichip& _a, Lexichip& _b);
		~Z80Unit();

		void setReset(bool _held);    // Z80_INITn, driven by T-MIX #3 SPO pins
		bool inReset() const { return m_reset; }
		void run(uint32_t _ticks);    // T-states

		// ASSUMPTION: bank selection hardware is not documented; the SRAM chip selects are generated by
		// Lexichip A (manual p. 7-35), so the select register most likely lives in its control area.
		void setBank(uint32_t _window, uint32_t _bank) { m_bank[_window & 1] = _bank & 3; }

		uint8_t peek(uint16_t _addr);
		uint16_t pc() const;
		uint64_t ticks() const { return m_ticks; }
		bool halted() const;

		std::function<void(uint16_t addr, uint8_t value)> onUnmappedWrite;

	private:
		uint8_t memRead(uint16_t _a);
		void memWrite(uint16_t _a, uint8_t _v);

		struct Cpu;
		std::unique_ptr<Cpu> m_cpu;
		Dpram& m_dpram;
		Lexichip& m_lexA;
		Lexichip& m_lexB;
		std::array<std::array<uint8_t, BankSize>, SramBanks> m_sram{};
		std::array<uint32_t, 2> m_bank{};
		bool m_reset = true;
		uint64_t m_ticks = 0;
	};
}
